export function resolveDefaultRegion() {
  const envRegion = (process.env.NEXT_PUBLIC_DEFAULT_REGION || 'US').toUpperCase();
  return REGION_PRESETS[envRegion] ? envRegion : 'US';
}

export function formatMoney(value, regionCode = 'US') {
  const preset = REGION_PRESETS[regionCode] || REGION_PRESETS.US;
  const numeric = Number(value ?? 0);
  const safeValue = Number.isNaN(numeric) ? 0 : numeric;
  try {
    return new Intl.NumberFormat(preset.locale, {
      style: 'currency',
      currency: preset.currency,
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }).format(safeValue);
  } catch {
    return `${preset.currencySymbol} ${safeValue.toFixed(2)}`;
  }
}

